export type TranslationKey = {
  [Section in keyof typeof TRANSLATIONS.en]: keyof typeof TRANSLATIONS.en[Section] extends string
    ? `${Section}.${keyof typeof TRANSLATIONS.en[Section] & string}`
    : never;
}[keyof typeof TRANSLATIONS.en];

function getTemplate(language: Language, key: TranslationKey): string {
  const [section, name] = key.split('.') as [keyof typeof TRANSLATIONS.en, string];
  const languageSection = TRANSLATIONS[language][section] as Record<string, string>;
  const fallbackSection = TRANSLATIONS.en[section] as Record<string, string>;
  return languageSection[name] ?? fallbackSection[name] ?? key;
}

export function translate(language: Language, key: TranslationKey, params: TranslationParams = {}): string {
  return getTemplate(language, key).replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
